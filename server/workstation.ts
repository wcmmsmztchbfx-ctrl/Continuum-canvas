import { createHash } from 'node:crypto'
import { join } from 'node:path'

/** Cookie used by the nickname-only workstation entry gate. */
export const WORKSTATION_USER_COOKIE = 'continuum-workstation-user'

/**
 * Workstation folders are deliberately human-readable while remaining safe
 * path components. The digest prevents two different nicknames that collapse
 * to the same display slug from sharing a workspace.
 */
export function workstationUserId(displayName: string): string {
  const normalized = displayName.trim()
  const slug = Array.from(normalized)
    // Cookie values are ASCII-only in practice. Keep the human-readable slug
    // for Latin names and rely on the digest for non-ASCII nicknames.
    .map((character) => /[A-Za-z0-9._-]/.test(character) ? character : '_')
    .join('')
    .replace(/_+/g, '_')
    .replace(/^[_-]+|[_-]+$/g, '')
    .slice(0, 48) || 'user'
  const digest = createHash('sha256').update(normalized, 'utf8').digest('hex').slice(0, 10)
  return `${slug}-${digest}`
}

export function normalizeWorkstationDisplayName(displayName: string): string {
  const normalized = displayName.trim()
  if (!normalized || Array.from(normalized).length > 32) {
    throw new Error('显示昵称长度必须在 1 到 32 个字符之间')
  }
  return normalized
}

export function workstationDataDir(dataDir: string, userId: string): string {
  // userId is generated by workstationUserId; this guard keeps callers from
  // ever turning a cookie value into a path traversal primitive.
  if (!/^[\p{L}\p{N}][\p{L}\p{N}._-]{0,79}$/u.test(userId)) {
    throw new Error('工作站用户标识无效')
  }
  return join(dataDir, 'workstation', userId)
}

export function workstationCookieValue(userId: string, displayName: string): string {
  return `${userId}.${encodeURIComponent(displayName)}`
}

export function parseWorkstationCookieValue(value: string | undefined): {
  userId: string
  displayName: string
} | undefined {
  if (!value) return undefined
  const separator = value.indexOf('.')
  if (separator <= 0) return undefined
  const userId = value.slice(0, separator)
  if (!/^[\p{L}\p{N}][\p{L}\p{N}._-]{0,79}$/u.test(userId)) return undefined
  let displayName: string
  try {
    displayName = normalizeWorkstationDisplayName(decodeURIComponent(value.slice(separator + 1)))
  } catch {
    return undefined
  }
  if (workstationUserId(displayName) !== userId) return undefined
  return { userId, displayName }
}
